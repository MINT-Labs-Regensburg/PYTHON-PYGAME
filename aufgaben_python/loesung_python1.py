# Lösung Aufgabe Python 1: Variablen

# 1. Variablen für Name, Alter und Größe erstellen
name = "Nicole"
alter = 12
groesse = 1.57

# 2. Variablen ausgeben
print(f"Ich heisse {name}, bin {alter} Jahre alt und {groesse} Meter gross")

# 3. Alter um ein Jahr erhöhen
alter += 1
print(f"Nächstes Jahr werde ich {alter} Jahre alt sein")

# 4. Summe aus zwei Zahlen berechnen
zahl1 = 10
zahl2 = 25
summe = zahl1 + zahl2
print(f"Die Summe von {zahl1} und {zahl2} ist {summe}")

# 5. Lieblingsfarbe abfragen und ausgeben
lieblingsfarbe = input("Was ist deine Lieblingsfarbe? ")
print(f"Deine Lieblingsfarbe ist {lieblingsfarbe}")
